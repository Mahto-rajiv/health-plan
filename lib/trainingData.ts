// ─── TRAINING PROGRAM ─────────────────────────────────────────────────────────
// Evidence basis:
// • Beginner linear progression: Raastad et al., NSCA guidelines
// • 4-day Upper/Lower split: optimal frequency for beginners (each muscle 2x/week)
//   Ralston et al. 2017 meta-analysis: 2x/week superior to 1x for hypertrophy
// • RIR 2-3 for beginners: prevents technique breakdown, manages recovery
// • Progressive overload: add weight when completing top of rep range with RIR≥2
// • Deload: every 6-8 weeks, reduce volume by 40-50% (Zourdos et al.)
// • Rest periods: 2-3 min compound, 60-90s isolation (Schoenfeld et al. 2016)

